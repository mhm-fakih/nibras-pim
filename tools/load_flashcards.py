#!/usr/bin/env python3
"""
Loads a gathered flash-card bank (flashcards.jsonl) into the backend's `flash_card` table.

    python3 tools/gather_flashcards.py .        # notes.jsonl -> flashcards.jsonl
    python3 tools/load_flashcards.py flashcards.jsonl | mysql db_nibras2

Writes SQL to stdout rather than connecting itself, so the load can be read before it is run and
piped at whichever database is meant.

The load is IDEMPOTENT: `card_key` is the passage's content hash and carries a unique index, so
INSERT IGNORE means re-running adds nothing and — importantly — does not reset the state of a card
that has already been reviewed.

This is a ONE-TIME gathering by design. Notes written or deleted afterwards do not change the bank;
the job is to get through this material once, not to keep up with it.
"""

import json
import sys


def esc(v):
    """MySQL string literal. Escapes exactly what a string literal can contain."""
    if v is None:
        return "NULL"
    s = str(v)
    s = (s.replace("\\", "\\\\")
          .replace("'", "\\'")
          .replace("\n", "\\n")
          .replace("\r", "\\r")
          .replace("\x00", "")
          .replace("\x1a", ""))
    return "'" + s + "'"


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "flashcards.jsonl"
    rows, position = [], 0
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            o = json.loads(line)
            if "text" not in o:        # the bank's header line
                continue
            rows.append((o["id"], o["note"], o.get("date"), o["text"],
                         1 if o.get("rtl") else 0, o.get("topic", "o"), position))
            position += 1

    print("-- Generated by tools/load_flashcards.py — safe to re-run.")
    print("SET NAMES utf8mb4;")
    # Batched: 22,000 single-row INSERTs is a round trip each, and one giant statement would blow
    # max_allowed_packet.
    BATCH = 500
    cols = ("card_key, note_id, written_on, passage, rtl, topic, position, "
            "state, date_created, last_updated")
    for i in range(0, len(rows), BATCH):
        chunk = rows[i:i + BATCH]
        values = ",\n".join(
            f"({esc(k)},{n},{esc(d)},{esc(t)},{r},{esc(tp)},{p},'NEW',NOW(),NOW())"
            for (k, n, d, t, r, tp, p) in chunk)
        print(f"INSERT IGNORE INTO flash_card ({cols}) VALUES\n{values};")
    print(f"-- {len(rows)} cards", file=sys.stderr)


if __name__ == "__main__":
    main()
